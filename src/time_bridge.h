// The world clock: whole seconds 0x4f0c80 plus the milliseconds since 0x4997d0 passed 0x4f0c90. The game's own
// getter 0x17cf80 and setter 0x17cfc0 are called rather than the globals touched, so the arithmetic stays theirs.
namespace worldtime {
using Get=int64_t(*)();using Set=void(*)(uint32_t);
static Get get=nullptr;static Set set=nullptr;
static bool available(){
 // Whole functions: both are short, and each byte is part of the contract (RIP-relative globals included).
 const unsigned char getter[]={0x8b,0x0d,0x4a,0xc8,0x31,0x00,0x8b,0x05,0x04,0x3d,0x37,0x00,0x48,0x29,0xc1,0x48,0xb8,0xcf,0xf7,0x53,0xe3,0xa5,0x9b,0xc4,0x20,
  0x48,0xf7,0xe9,0x48,0xc1,0xfa,0x07,0x48,0xc1,0xe9,0x3f,0x48,0x01,0xca,0x8b,0x05,0xd3,0x3c,0x37,0x00,0x48,0x01,0xd0,0xc3};
 const unsigned char setter[]={0x89,0x0d,0xba,0x3c,0x37,0x00,0x8b,0x05,0x04,0xc8,0x31,0x00,0x89,0x05,0xbe,0x3c,0x37,0x00,0xc3};
 return gamebridge::operation(base+0x17cf80,getter,sizeof getter)&&gamebridge::operation(base+0x17cfc0,setter,sizeof setter);
}
static bool read(int64_t& seconds){
 if(!worldPulse||!get)return false;
 __try{seconds=get();return true;}__except(EXCEPTION_EXECUTE_HANDLER){return false;}
}
static bool write(uint32_t seconds){
 if(!worldPulse||!set||!gamebridge::backupDone)return false;
 __try{set(seconds);return true;}__except(EXCEPTION_EXECUTE_HANDLER){return false;}
}
}
